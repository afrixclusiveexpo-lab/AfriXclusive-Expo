import { expect, test, type Page } from '@playwright/test';
import { randomUUID } from 'node:crypto';
async function join(page: Page, name: string, role = 'founder') {
  await page.goto('/join');
  await page.getByLabel('Your name', { exact: true }).fill(name);
  await page.getByLabel('Email address', { exact: true }).fill(`${randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('Unique browser development password!');
  await page.getByLabel('What brings you here?').selectOption(role);
  await page.getByRole('button', { name: 'Create my account' }).click();
  await expect(page.getByRole('heading', { name: new RegExp(`Keep building, ${name.split(' ')[0]}`) })).toBeVisible();
}
