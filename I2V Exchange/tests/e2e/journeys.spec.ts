test('creator draft → safe publication → watchlist → collaboration → founder response', async ({ page, browser }) => {
  await join(page, 'Tariro Builder');
  await page.getByRole('button', { name: 'Create a project', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Start a private project' });
  const title = `Browser trial ${randomUUID().slice(0, 7)}`;
  await editor.getByLabel('Project name', { exact: true }).fill(title);
  await editor.getByLabel('Safe-to-share summary', { exact: true }).fill('A practical test of a repairable irrigation sensor with a deliberately public, non-confidential summary.');
  await editor.getByLabel('Location', { exact: true }).fill('Harare, Zimbabwe');
  await editor.getByLabel('Private notes', { exact: false }).fill('BROWSER_CONFIDENTIAL_NOTE_NEVER_PUBLISH');
  await editor.getByRole('button', { name: 'Save private draft' }).click();
  await expect(editor).not.toBeVisible();
  const owned = page.locator('.workspace-project').filter({ has: page.getByRole('heading', { name: title }) });
  await expect(owned.getByText('Private draft', { exact: true })).toBeVisible();
  expect(await (await page.request.get(`/api/projects?q=${encodeURIComponent(title)}`)).json()).toEqual([]);
  await owned.getByRole('button', { name: 'Preview & publish' }).click();
  const preview = page.getByRole('dialog', { name: 'Your public preview' });
  await expect(preview).not.toContainText('BROWSER_CONFIDENTIAL_NOTE_NEVER_PUBLISH');
  await preview.getByLabel('Who holds rights to this work?').selectOption('personal');
  await preview.getByRole('checkbox').check();
  await preview.getByRole('button', { name: 'Publish approved summary' }).click();
  await expect(preview).not.toBeVisible();
  await owned.getByRole('link', { name: 'View public page' }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  const publicUrl = page.url();
  await page.getByRole('button', { name: 'Save to watchlist', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Remove from watchlist', exact: true })).toBeVisible();
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5173' });
  const other = await context.newPage();
  try {
    await join(other, 'Rudo Partner', 'investor');
    await other.goto(publicUrl);
    await expect(other.locator('body')).not.toContainText('BROWSER_CONFIDENTIAL_NOTE_NEVER_PUBLISH');
    await other.getByLabel('How would you like to help?').fill('I would like to help design a field trial using only the public project goals.');
    await other.getByRole('button', { name: 'Request collaboration' }).click();
    await expect(other.getByRole('status')).toContainText('founder’s inbox');
    await page.goto('/network');
    const request = page.locator('.request-card').filter({ hasText: 'Rudo Partner' });
    await request.getByLabel('Response', { exact: true }).fill('Let’s work on the public trial plan.');
    await request.getByRole('button', { name: 'Approve request' }).click();
    await expect(request.getByText('approved', { exact: true })).toBeVisible();
    await other.goto('/network');
    await expect(other.getByText('Let’s work on the public trial plan.')).toBeVisible();
    const projectId = new URL(publicUrl).pathname.split('/').at(-1);
    expect((await other.request.get(`/api/projects/${projectId}/private`)).status()).toBe(404);
  } finally {
    await context.close();
    const projectId = new URL(publicUrl).pathname.split('/').at(-1);
    await page.request.post(`/api/projects/${projectId}/unpublish`, { headers: { Origin: 'http://127.0.0.1:5173' }, data: {} });
  }
});
test('network failure has an actionable retry and preserves guest discovery', async ({ page }) => {
  await page.route('**/api/projects', route => route.abort('failed'));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Let’s try that again.' })).toBeVisible();
  await page.unroute('**/api/projects');
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.locator('.project-card')).toHaveCount(4);
});
